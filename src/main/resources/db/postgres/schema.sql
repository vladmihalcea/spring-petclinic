CREATE TABLE IF NOT EXISTS vets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name  TEXT
);
CREATE INDEX IF NOT EXISTS vets_last_name_idx ON vets (last_name);

CREATE TABLE IF NOT EXISTS specialties (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE INDEX IF NOT EXISTS specialties_name_idx ON specialties (name);

CREATE TABLE IF NOT EXISTS vet_specialties (
  vet_id       INT NOT NULL REFERENCES vets (id),
  specialty_id INT NOT NULL REFERENCES specialties (id),
  PRIMARY KEY (vet_id, specialty_id)
);
-- Replace the UNIQUE constraint of the tables created by the previous schema with a Primary Key.
-- The block is single-quoted since the Spring SQL script splitter doesn't support dollar quoting.
DO '
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = ''vet_specialties''::regclass AND contype = ''p'') THEN
    ALTER TABLE vet_specialties DROP CONSTRAINT IF EXISTS vet_specialties_vet_id_specialty_id_key;
    ALTER TABLE vet_specialties ADD PRIMARY KEY (vet_id, specialty_id);
  END IF;
END';
CREATE INDEX IF NOT EXISTS vet_specialties_specialty_id_idx ON vet_specialties (specialty_id);

CREATE TABLE IF NOT EXISTS types (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE INDEX IF NOT EXISTS types_name_idx ON types (name);

CREATE TABLE IF NOT EXISTS owners (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name  TEXT,
  address    TEXT,
  city       TEXT,
  telephone  TEXT
);
CREATE INDEX IF NOT EXISTS owners_last_name_idx ON owners (last_name);

CREATE TABLE IF NOT EXISTS pets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT,
  birth_date DATE,
  type_id    INT NOT NULL REFERENCES types (id),
  owner_id   INT REFERENCES owners (id)
);
CREATE INDEX IF NOT EXISTS pets_name_idx ON pets (name);
CREATE INDEX IF NOT EXISTS pets_owner_id_idx ON pets (owner_id);
CREATE INDEX IF NOT EXISTS pets_type_id_idx ON pets (type_id);

CREATE TABLE IF NOT EXISTS visits (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      INT REFERENCES pets (id),
  visit_date  DATE,
  description TEXT
);
CREATE INDEX IF NOT EXISTS visits_pet_id_idx ON visits (pet_id);

CREATE SEQUENCE IF NOT EXISTS vets_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS specialties_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS types_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS owners_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS pets_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS visits_seq START WITH 1 INCREMENT BY 1;
